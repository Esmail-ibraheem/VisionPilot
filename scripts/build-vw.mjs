function readSource(file) {
  const buf = fs.readFileSync(file);
  // world/js/math/utils.js is UTF-16 LE with a BOM upstream
  if (buf[0] === 0xff && buf[1] === 0xfe) return buf.toString('utf16le').replace(/^﻿/, '');
  return buf.toString('utf8').replace(/^﻿/, '');
}

const declared = new Set();
const parts = [];
for (const rel of order) {
  let src = readSource(path.join(root, rel)).replace(/\r\n/g, '\n');
  // Drop duplicate top-level function declarations (phase-1 utils.js repeats lerp/getIntersection/getRandomColor).
  src = src.replace(/^function\s+([A-Za-z_$][\w$]*)\s*\([^)]*\)\s*\{[\s\S]*?\n\}\n?/gm, (m, name) => {
    if (declared.has(name)) return `/* duplicate ${name} omitted */\n`;
    declared.add(name);
    return m;
  });
  parts.push(`// ───── ${rel} ─────\n${src.trim()}\n`);
}
let bundle = parts.join('\n');

// Patches (each must apply exactly once).
const patches = [
  // GraphEditor.display() draws with a page-global `ctx`; use the editor's own context.
  ["new Segment(this.selected, intent).draw(ctx, { dash: [3, 3] });", "new Segment(this.selected, intent).draw(this.ctx, { dash: [3, 3] });"],
  // Car builds an <img>/<canvas> for its 2D sprite; skip that outside a browser (tests) — the app renders cars itself.
  ["        this.img=new Image();\n        this.img.src=\"car.png\"\n\n        this.mask=document.createElement(\"canvas\");", "        if(typeof document===\"undefined\"){return;}\n        this.img=new Image();\n        this.img.src=\"car.png\"\n\n        this.mask=document.createElement(\"canvas\");"],
  // Start marking loads its sprite eagerly; same guard.
  ["      this.img = new Image();\n      this.img.src = \"car.png\";\n      this.type = \"start\";", "      this.type = \"start\";\n      if (typeof document === \"undefined\") return;\n      this.img = new Image();\n      this.img.src = \"car.png\";"],
];
for (const [from, to] of patches) {
  const n = bundle.split(from).length - 1;
  if (n !== 1) throw new Error(`patch expected once, found ${n}: ${from.slice(0, 60)}`);
  bundle = bundle.replace(from, to);
}

