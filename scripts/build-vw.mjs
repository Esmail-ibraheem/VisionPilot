fs.mkdirSync('src/vw', { recursive: true });
fs.writeFileSync('src/vw/virtual-world.js', header + bundle + footer);
console.log(`src/vw/virtual-world.js: ${(bundle.length / 1024).toFixed(0)} kB from ${order.length} files`);
