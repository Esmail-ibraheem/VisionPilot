/**
 * Bundle gniziemazity/virtual-world (MIT, phase "11. MiniMap") into one ES module the app imports.
 *
 *   node scripts/build-vw.mjs [path-to-virtual-world-clone]
 *
 * The upstream files are plain browser globals loaded by <script> tags, so they are concatenated
 * in dependency order inside a single module scope and exported at the end. Only minimal patches
 * are applied (listed below); the algorithms are untouched.
 */
